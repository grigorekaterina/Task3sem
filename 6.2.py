group_1 = [
    "Антонова", "Васильева", "Григоренко", "Калинина", "Комарова",
    "Ларионов", "Лебедев", "Максименко", "Семенчук", "Степанова"
]

group_2 = [
    "Дмитриев", "Соколов", "Иванов", "Козлов", "Новиков",
    "Морозов", "Волков", "Зайцев", "Борисов", "Павлов"
]

team_list = group_1[:2] + group_1[6:9] + group_2[4:9]
team_tuple = tuple(team_list)

# 2.2. Вывод исходных данных и результата
print("Группа 1:", group_1)
print("Группа 2:", group_2)
print("Сборная команда (кортеж):", team_tuple)

# 2.3. Длина кортежа
print(f"Количество участников в команде: {len(team_tuple)}")

# 2.4. Сортировка кортежа по алфавиту
sorted_team = tuple(sorted(team_tuple))
print("Отсортированная команда:", sorted_team)

# 2.5. Поиск "Иванов" и подсчет количества
trgt = "Иванов"
if trgt in team_tuple:
    cnt = team_tuple.count(trgt)
    print(f"Студент {trgt} есть в команде. Встречается {cnt} раз(а).")
else:
    print(f"Студента {trgt} в команде нет.")