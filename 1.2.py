a= int(input("Введите значение первой переменной. a = "))
b= int(input("Введите значение второй переменной. b = "))

summa = a + b
minus = a - b
umn = a * b
dele = a / b

print("Результаты арифметических действий")
print(f"Сложение - {a} + {b} = {summa}")
print(f"Вычитание - {a} - {b} = {minus}")
print(f"Умножение -  {a} * {b} ={umn}")
print(f"Деление -  {a} / {b} = {dele}")